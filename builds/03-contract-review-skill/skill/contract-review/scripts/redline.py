"""Write a redlined .docx and a one-page issues memo from a contract review.

Part of the contract-review Skill. Redline convention:
  OK         -> original text, unchanged
  negotiate  -> original struck through in red, clause library fallback inserted (blue, underlined),
                plus a Word comment with the reason
  escalate   -> original highlighted yellow, plus a Word comment asking for a partner decision
"""
from __future__ import annotations

from pathlib import Path

from docx import Document
from docx.enum.text import WD_COLOR_INDEX
from docx.shared import Pt, RGBColor

RED, BLUE = RGBColor(0xC0, 0x1F, 0x1F), RGBColor(0x1F, 0x4E, 0xC0)


def write_redline(contract: dict, review: dict, library: dict, path: Path) -> dict:
    """review = {"clauses": [{"clause_id", "clause_type", "decision", "reason", ...}]}"""
    calls = {c["clause_id"]: c for c in review["clauses"]}
    doc = Document()
    doc.styles["Normal"].font.size = Pt(10.5)
    doc.add_heading(f"{contract['title']} - redline", level=1)
    doc.add_paragraph(f"{contract['contract_id']} | Counterparty: {contract['counterparty']} | "
                      f"Reviewed against playbook for the service provider")
    counts = {"OK": 0, "negotiate": 0, "escalate": 0}
    for cl in contract["clauses"]:
        call = calls.get(cl["clause_id"])
        doc.add_heading(cl["heading"], level=2)
        p = doc.add_paragraph()
        if call is None or call["decision"] == "OK":
            p.add_run(cl["text"])
            counts["OK"] += call is not None
            continue
        counts[call["decision"]] += 1
        if call["decision"] == "negotiate" and call["clause_type"] in library:
            old = p.add_run(cl["text"])
            old.font.strike, old.font.color.rgb = True, RED
            p.add_run(" ")
            new = p.add_run(library[call["clause_type"]])
            new.font.underline, new.font.color.rgb = True, BLUE
            doc.add_comment([old, new], text=f"Negotiate: {call['reason']}", author="Contract review Skill", initials="CR")
        else:
            run = p.add_run(cl["text"])
            run.font.highlight_color = WD_COLOR_INDEX.YELLOW
            doc.add_comment(run, text=f"Escalate to partner: {call['reason']}", author="Contract review Skill", initials="CR")
    doc.save(path)
    return counts


def write_memo(contract: dict, review: dict, rules: dict, library: dict, path: Path) -> str:
    issues = [c for c in review["clauses"] if c["decision"] != "OK"]
    heads = {c["clause_id"]: c["heading"] for c in contract["clauses"]}
    lines = [f"# Issues memo - {contract['contract_id']} ({contract['type']})", "",
             f"**Contract:** {contract['title']}  ",
             f"**Counterparty:** {contract['counterparty']}  ",
             f"**Clauses reviewed:** {len(review['clauses'])} | "
             f"**OK:** {sum(c['decision'] == 'OK' for c in review['clauses'])} | "
             f"**Negotiate:** {sum(c['decision'] == 'negotiate' for c in review['clauses'])} | "
             f"**Escalate:** {sum(c['decision'] == 'escalate' for c in review['clauses'])}", ""]
    esc = [c for c in issues if c["decision"] == "escalate"]
    if esc:
        lines += ["## Partner decisions needed", ""]
        for c in esc:
            lines.append(f"- **{heads[c['clause_id']]}** ({c['extracted_value']}): {c['reason']}")
        lines.append("")
    neg = [c for c in issues if c["decision"] == "negotiate"]
    if neg:
        lines += ["## Proposed changes", "", "| Clause | Found | Playbook position | Proposed fallback |", "|---|---|---|---|"]
        for c in neg:
            lines.append(f"| {heads[c['clause_id']]} | {c['extracted_value']} | {rules[c['clause_type']]['position']} | "
                         f"{rules[c['clause_type']]['fallback']} |")
        lines.append("")
    if not issues:
        lines += ["No issues. Every clause meets the playbook position.", ""]
    lines.append("_Generated by the contract-review Skill. Fallback wording is taken verbatim from clause_library.json._")
    text = "\n".join(lines)
    path.write_text(text)
    return text
